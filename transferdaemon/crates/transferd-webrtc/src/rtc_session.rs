#[derive(Debug, thiserror::Error)]
pub enum WebRtcError {
    #[error("Peer connection error: {0}")]
    PeerConnectionError(String),

    #[error("SDP error: {0}")]
    SdpError(String),

    #[error("ICE error: {0}")]
    IceError(String),

    #[error("Media error: {0}")]
    MediaError(String),

    #[error("Internal error: {0}")]
    Internal(String),
}

#[cfg(test)]
mod tests {
    use super::inject_b_as;

    #[test]
    fn b_as_is_injected_after_every_media_line() {
        let sdp = "v=0\no=- 0 0 IN IP4 0.0.0.0\nm=audio 9 UDP/TLS/RTP/SAVPF 111\na=mid:0\nm=video 9 UDP/TLS/RTP/SAVPF 96\na=mid:1\n";
        let out = inject_b_as(sdp, 1500);
        assert!(out.contains("m=audio 9 UDP/TLS/RTP/SAVPF 111\nb=AS:1500\n"));
        assert!(out.contains("m=video 9 UDP/TLS/RTP/SAVPF 96\nb=AS:1500\n"));
        assert_eq!(out.matches("b=AS:1500").count(), 2);
    }

    #[test]
    fn zero_kbps_leaves_sdp_untouched() {
        let sdp = "m=audio 9 UDP/TLS/RTP/SAVPF 111\n";
        assert_eq!(inject_b_as(sdp, 0), sdp);
    }
}
