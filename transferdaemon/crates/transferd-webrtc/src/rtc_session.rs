//! RtcCallSession — real WebRTC peer connection via webrtc-rs.
//!
//! This implementation uses the `webrtc-rs` crate for actual peer-to-peer
//! media transport. It implements the same interface as `SimulatedCallSession`
//! but with real DTLS-SRTP, ICE, and codec negotiation.
//!
//! Enable with the `real-webrtc` feature flag.

