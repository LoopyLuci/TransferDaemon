// Peer connection setup
// ---------------------------------------------------------------------------

async fn setup_peer_connection(
    call_id: &str,
) -> Result<
    (
        Arc<RTCPeerConnection>,
        mpsc::Sender<IceCandidateInit>,
        mpsc::Receiver<IceCandidateInit>,
        Option<Arc<TrackLocalStaticRTP>>,
        mpsc::Receiver<AudioSamples>,
        Vec<tokio::task::JoinHandle<()>>,
    ),
    WebRtcError,
> {
    let tasks = Vec::new();

    // Create media engine and register the codecs we use (opus audio, VP8 video).
    // `MediaEngine::default()` is an empty codec table — without registration,
    // SDP offer/answer generation fails with `ErrSenderWithNoCodecs`.
    let mut media_engine = MediaEngine::default();
    media_engine.register_default_codecs()
        .map_err(|e| WebRtcError::MediaError(format!("register_default_codecs: {e}")))?;

    // Create setting engine
    let setting_engine = SettingEngine::default();

    // Create API
    let api = APIBuilder::new()
        .with_media_engine(media_engine)
        .with_setting_engine(setting_engine)
        .build();

    // Create peer connection
    let config = RTCConfiguration::default();

    let peer_connection = Arc::new(api.new_peer_connection(config).await
        .map_err(|e| WebRtcError::PeerConnectionError(e.to_string()))?);

    // Create audio track.  `clock_rate`/`channels` must match the opus codec
    // registered in the media engine so the SDP offer/answer population finds it.
    let audio_track = Arc::new(TrackLocalStaticRTP::new(
        RTCRtpCodecCapability {
            mime_type: "audio/opus".to_string(),
            clock_rate: 48000,
            channels: 2,
            ..Default::default()
        },
        format!("audio-{call_id}"),
        format!("transferd-audio-{call_id}"),
    ));

    let _audio_transceiver = peer_connection.add_transceiver_from_track(
        Arc::clone(&audio_track) as Arc<dyn TrackLocal + Send + Sync>,
        None,
    ).await.map_err(|e| WebRtcError::PeerConnectionError(e.to_string()))?;

    // ICE candidate channel
    let (ice_tx, ice_rx) = mpsc::channel(16);

    // Monitor connection state
    peer_connection.on_peer_connection_state_change(Box::new(move |state: RTCPeerConnectionState| {
        Box::pin(async move {
            tracing::info!("[WebRTC] Connection state: {:?}", state);
        })
    }));

    // Handle incoming tracks from remote peer
    let (remote_audio_tx, remote_audio_rx) = mpsc::channel(64);
    peer_connection.on_track(Box::new(move |track, _receiver, _transceiver| {
        let remote_audio_tx = remote_audio_tx.clone();
        Box::pin(async move {
            // Read RTP packets from the remote track
            loop {
                match track.read_rtp().await {
                    Ok((packet, _)) => {
                        // Parse RTP header (12 bytes minimum)
                        if packet.payload.len() < 12 {
                            continue;
                        }

                        // Extract payload (skip 12-byte RTP header)
                        let payload = &packet.payload[12..];

                        // Convert i16 PCM samples to f32
                        // The payload contains i16 samples in big-endian format
                        let samples: AudioSamples = payload
                            .as_chunks::<2>()
                            .0
                            .iter()
                            .map(|chunk| {
                                let i16_sample = i16::from_be_bytes([chunk[0], chunk[1]]);
                                i16_sample as f32 / 32767.0
                            })
                            .collect();

                        if !samples.is_empty() && remote_audio_tx.send(samples).await.is_err() {
                            tracing::debug!("[WebRTC] Remote audio channel closed");
                            break;
                        }
                    }
                    Err(e) => {
                        tracing::error!("[WebRTC] Error reading RTP: {e}");
                        break;
                    }
                }
            }
        })
    }));

    Ok((
        peer_connection,
        ice_tx,
        ice_rx,
        Some(audio_track),
        remote_audio_rx,
        tasks,
    ))
}

