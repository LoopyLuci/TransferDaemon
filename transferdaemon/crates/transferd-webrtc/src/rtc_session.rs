fn gen_id(prefix: &str) -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .subsec_nanos();
    format!("{prefix}-{nanos:08x}")
}

/// Convert RGBA pixel data to I420 (YUV 4:2:0) format for VP8 encoding.
#[allow(dead_code)]
fn rgba_to_i420(rgba: &[u8], width: u32, height: u32) -> Vec<u8> {
    let w = width as usize;
    let h = height as usize;
    let y_size = w * h;
    let uv_size = (w / 2) * (h / 2);

    let mut i420 = vec![0u8; y_size + uv_size * 2];

    // Convert RGBA to YUV
    for y in 0..h {
        for x in 0..w {
            let i = (y * w + x) * 4;
            let r = rgba[i] as f32;
            let g = rgba[i + 1] as f32;
            let b = rgba[i + 2] as f32;

            // Y component
            let y_val = (0.299 * r + 0.587 * g + 0.114 * b).clamp(0.0, 255.0) as u8;
            i420[y * w + x] = y_val;

            // U and V components (subsampled 2x2)
            if y % 2 == 0 && x % 2 == 0 {
                let u_val = (-0.169 * r - 0.331 * g + 0.500 * b + 128.0).clamp(0.0, 255.0) as u8;
                let v_val = (0.500 * r - 0.419 * g - 0.081 * b + 128.0).clamp(0.0, 255.0) as u8;
                let uv_idx = y_size + (y / 2) * (w / 2) + (x / 2);
                i420[uv_idx] = u_val;
                i420[uv_idx + uv_size] = v_val;
            }
        }
    }

    i420
}

